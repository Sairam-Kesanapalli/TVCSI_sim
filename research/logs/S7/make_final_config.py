"""S7: write configs/final.yaml = configs/default.yaml + the final-run overrides below.

From the repository root:  <venv>/Scripts/python research/logs/S7/make_final_config.py
The final experiments use the S6 gate choice (trained codec + persistence predictor) and write
to new dated folders, so the Phase 2 results in results/ and figures/ are never overwritten.
"""
import yaml

from tvcsi.config import ROOT, apply_overrides, load_config

OVERRIDES = {
    "models": "trained",                                     # trained codec + Persistence (S6 gate)
    "paths.results": "results/final_20261103",
    "paths.figures": "figures/final_20261103",
}


def main() -> None:
    cfg = apply_overrides(load_config(), OVERRIDES)
    header = ("# GENERATED by research/logs/S7/make_final_config.py: configs/default.yaml + " +
              ", ".join(f"{k}={v}" for k, v in OVERRIDES.items()) +
              ".\n# Do not edit by hand; edit default.yaml or the overrides and regenerate.\n")
    (ROOT / "configs" / "final.yaml").write_text(header + yaml.safe_dump(cfg, sort_keys=False, width=110))
    print("wrote configs/final.yaml")


if __name__ == "__main__":
    main()
